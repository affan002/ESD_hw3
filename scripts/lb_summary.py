#!/usr/bin/env python3
"""Build the A3 results table (Part D: one row per run and interface) from docs/results/a3/.

Reads each run's client summary (lb_load.py) and server stats (lb_run_stats.py) and
writes docs/results/a3/summary.md with the brief's columns: run/interface, policy and
fault, target/actual req/s, A/B/C shares, client p95, error rate. The explanation
column is in REPORT.md. Standard library only.

    python3 scripts/lb_summary.py
"""

import json
from pathlib import Path

R = Path(__file__).resolve().parent.parent / "docs" / "results" / "a3"
RUNS = [
    ("b_baseline", "B baseline", "A only, no fault"),
    ("c_round_robin", "C round robin", "round robin 1:1:1, no fault"),
    ("d_weighted", "D1 weighted", "round robin 2:1:1, no fault"),
    ("d_delay_rr", "D2 delay · RR", "round robin 1:1:1, B +200 ms"),
    ("d_delay_lr", "D2 delay · LR", "least request (P2C), B +200 ms"),
    ("d_failure", "D3 failure", "round robin, B stopped t=30 s, started t=70 s"),
]


def main() -> int:
    rows = ["| Run / interface | Policy and fault | Target / actual req/s | A / B / C share | Client p95 | Error rate |",
            "|---|---|---|---|---|---|"]
    for name, label, policy in RUNS:
        for iface in ("http", "grpc"):
            path = R / f"{name}_{iface}.json"
            if not path.exists():
                continue
            c = json.loads(path.read_text())
            shares = c["replica_shares_pct"]
            share = " / ".join(f"{shares.get(r, 0):.1f}" for r in "ABC")
            rows.append(f"| {label} · {'HTTP' if iface == 'http' else 'gRPC'} | {policy} | "
                        f"{c['target_rps']:g} / {c['actual_rps']:.2f} | {share} % | "
                        f"{c['client_latency_ms']['p95']:.1f} ms | "
                        f"{c['error_rate_pct']:.2f} % ({c['failures']}/{c['sent']}) |")
    text = ("# A3 results summary\n\nGenerated by `scripts/lb_summary.py` from the run files in this folder. "
            "Shares are of successful requests, from the client's `x-replica` (identical to Prometheus and "
            "Envoy's per-endpoint counts in every run). 120 s per run, open loop, no retries.\n\n"
            + "\n".join(rows) + "\n")
    (R / "summary.md").write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
